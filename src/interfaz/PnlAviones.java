    private void cargarAerolineas(){
        cmbAerolinea.removeAllItems();
        List<Aerolinea> aerolineas = aerolineaLogica.listarAerolineas();
        for (Aerolinea a : aerolineas) {
            cmbAerolinea.addItem(a);
        }
    }
    
    private void cargarTablasAviones(){
        DefaultTableModel modelo = (DefaultTableModel) tblAviones.getModel();
        modelo.setRowCount(0);
        
        List<Avion> aviones = avionLogica.listarAviones();
        for (Avion a : aviones) {
            Object [] fila = {
                a.getIdAvion(),
                a.getAerolinea().getNombre(),
                a.getModelo(),
                a.getCapacidad(),
                a.getEstado()
            };
            modelo.addRow(fila);
        }
    }
    private void limpiarFormulario(){
        txtModelo.setText("");
        txtCapacidad.setText("");
        cmbEstado.setSelectedIndex(0);
    }
    public void actualizarDatos() {
        cargarAerolineas();
        cargarTablasAviones();
    }

